const STRINGS = { es: ES, pt: PT, en: EN };

/* Devuelve la función de traducción para un idioma.
   Si falta una clave en el idioma elegido cae al español,
   de modo que nunca se muestra una clave cruda al usuario. */
/* Idioma en que deben rotularse las SECCIONES DEL DOCUMENTO.
   No es el idioma de la interfaz: un plan para Brasil se rotula en
   portugués aunque el docente navegue en inglés, porque el documento
   se imprime y se entrega. Los países cuya lengua no está soportada
   en la interfaz (Haití, Surinam) caen al español. */
export function docLang(countryLang) {
  return ["es", "pt", "en"].includes(countryLang) ? countryLang : "es";
}

export function makeT(lang) {
  const dict = STRINGS[lang] || ES;
  return (key) => (dict[key] !== undefined ? dict[key] : ES[key] !== undefined ? ES[key] : key);
}

